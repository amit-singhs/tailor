/**
 * The skill taxonomy: known skills and the names people write them as.
 *
 * Code uses this to FIND candidate skills in a resume or job post. It is meant
 * to over-find: Jev then verifies each candidate in context (lib/jev/questions.ts),
 * which is what removes false hits like "go" the verb or "spring" the season.
 *
 * Contributing: add a line with `s(name, category, aliases?, { cs: true })`.
 * - Aliases are matched case-insensitively unless `cs` (case-sensitive) is set.
 * - Set `cs` for names that are also common words or single letters.
 * - Keep one entry per real skill; put spelling variants in aliases.
 * Run `npm test` to check for duplicate ids and aliases.
 */
import { slugify } from '../text';
import type { SkillCategory, TaxonomySkill } from '../types';

function s(name: string, category: SkillCategory, aliases: string[] = [], opts: { cs?: boolean; id?: string } = {}): TaxonomySkill {
  return { id: opts.id ?? slugify(name), name, category, aliases, caseSensitive: opts.cs };
}

